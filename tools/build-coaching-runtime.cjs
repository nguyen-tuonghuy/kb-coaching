// Deterministic packaging for static GitHub Pages. Author modules, not the bundle.
const fs=require('node:fs');
const path=require('node:path');
const root=path.resolve(__dirname,'..');
const sources=['page-shell','utils','context','data','match-data','calculations','video','auth','session','player-portal','match-capture','catalogs','groups','match-library','analysis','statistics','bootstrap'];
const target=path.join(root,'js/shared/coaching.bundle.js');
const output='/* GENERATED by node tools/build-coaching-runtime.cjs. Do not edit this file. */\n'+sources.map(name=>{
  const file=`js/shared/${name}.js`;
  return `\n/* BEGIN ${file} */\n${fs.readFileSync(path.join(root,file),'utf8').trimEnd()}\n/* END ${file} */\n`;
}).join('');
if(process.argv.includes('--check')){
  if(!fs.existsSync(target)||fs.readFileSync(target,'utf8')!==output){
    console.error('Shared runtime is stale. Run: node tools/build-coaching-runtime.cjs');
    process.exitCode=1;
  }else console.log('Shared runtime matches all source modules.');
}else{
  fs.writeFileSync(target,output);
  console.log(`Built ${path.relative(root,target)} (${Buffer.byteLength(output)} bytes, ${sources.length} modules).`);
}
